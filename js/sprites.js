/* ── tiny sprite renderer ─────────────────────────────────────── */
function makeCanvas(w, h) {
  const c = document.createElement('canvas');
  c.width = w; c.height = h;
  return c;
}
function renderSprite(rows, palette, flip) {
  const c = makeCanvas(16, rows.length), ctx = c.getContext('2d');
  rows.forEach((row, y) => {
    if (row.length !== 16) console.warn('sprite row length', row.length, row);
    for (let x = 0; x < 16; x++) {
      const col = palette[row[x]];
      if (col) { ctx.fillStyle = col; ctx.fillRect(flip ? 15 - x : x, y, 1, 1); }
    }
  });
  return c;
}

